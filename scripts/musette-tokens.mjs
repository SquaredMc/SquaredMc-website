// Writes public/musette/css/tokens.css from the Musette app's design tokens
// (design/tokens.json in SquaredMc/Training-side-kick), so the site and the
// app share one palette and type scale:
//
//   node scripts/musette-tokens.mjs ~/Developer/workout-pick/design/tokens.json > public/musette/css/tokens.css
//
// Names follow the token paths: Semantic/color/text/primary becomes
// --ms-text-primary, the same token as Palette.textPrimary in Swift and
// text/primary in Figma. Values the site needs that the app doesn't have are
// in SITE_ONLY at the bottom; change those here, not in the output.

import { readFileSync } from "node:fs"

const path = process.argv[2]
if (!path) {
    console.error("usage: node scripts/musette-tokens.mjs <path to design/tokens.json>")
    process.exit(1)
}
const tokens = JSON.parse(readFileSync(path, "utf8"))

// Walks a token group, calling visit(pathParts, token) for every leaf.
function walk(group, visit, parts = []) {
    for (const [key, value] of Object.entries(group)) {
        if (key.startsWith("$")) continue
        if (value && typeof value === "object" && "$value" in value) visit([...parts, key], value)
        else if (value && typeof value === "object") walk(value, visit, [...parts, key])
    }
}

function colour({ hex, alpha }) {
    if (alpha === 1) return hex
    const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16))
    return `rgb(${r} ${g} ${b} / ${alpha})`
}

// "{Primitives.color.pine.900}" -> "var(--ms-pine-900)"
function primitiveRef(ref) {
    const parts = ref.replace(/[{}]/g, "").split(".").slice(2)
    return `var(--ms-${parts.join("-")})`
}

const out = []
const line = (text = "") => out.push(text)

// Primitives
const primitives = []
walk(tokens.Primitives.color, (parts, token) => {
    primitives.push(`  --ms-${parts.join("-")}: ${colour(token.$value)};`)
})

// Semantic colours, per mode. Increased Contrast replaces a few of them.
const modes = { Light: [], Dark: [] }
const contrast = { Light: [], Dark: [] }
walk(tokens.Semantic.color, (parts, token) => {
    const name = `--ms-${parts.join("-")}`
    const figmaModes = token.$extensions["com.figma"].modes
    for (const mode of ["Light", "Dark"]) modes[mode].push(`  ${name}: ${primitiveRef(figmaModes[mode])};`)
    const more = token.$extensions["com.workoutpick.increasedContrast"]
    if (more) for (const mode of ["Light", "Dark"]) contrast[mode].push(`    ${name}: ${primitiveRef(more[mode])};`)
})

// Typography. Line height becomes a ratio and tracking becomes em, so a style
// still holds its shape when the site scales the size.
const stacks = {
    Manrope: "Manrope, system-ui, -apple-system, \"Segoe UI\", Roboto, sans-serif",
    "DM Mono": "\"DM Mono\", ui-monospace, \"SF Mono\", Menlo, monospace",
    // SF Pro in the app. system-ui is SF Pro on Apple devices.
    "SF Pro": "system-ui, -apple-system, BlinkMacSystemFont, \"Segoe UI\", Roboto, sans-serif",
}
const typeStyles = {}
walk(tokens.Typography.typography, (parts, token) => {
    const style = parts.slice(0, -1).join("-")
    ;(typeStyles[style] ??= {})[parts.at(-1)] = token.$value
})
const typography = Object.entries(typeStyles).map(([style, t]) => {
    const size = t["font-size"].value
    return [
        `  --ms-${style}-font: ${stacks[t["font-family"]]};`,
        `  --ms-${style}-weight: ${t["font-weight"]};`,
        `  --ms-${style}-size: ${size}px;`,
        `  --ms-${style}-line-height: ${+(t["line-height"].value / size).toFixed(3)};`,
        `  --ms-${style}-tracking: ${+(t["letter-spacing"].value / size).toFixed(4)}em;`,
    ].join("\n")
})

function dimensions(group, prefix) {
    const lines = []
    walk(group, (parts, token) => lines.push(`  --ms-${prefix}-${parts.join("-")}: ${token.$value.value}px;`))
    return lines
}

const SITE_ONLY = `  /* Site only: layout values the app doesn't have */
  --ms-web-maxw: 1248px;             /* includes the 48px side gutters */
  --ms-web-maxw-legal: 760px;
  --ms-web-section-y: 96px;
  --ms-web-header-h: 72px;`

line("/**")
line(" * Musette design tokens, from the app's design/tokens.json (Summit Signal).")
line(" * Generated by scripts/musette-tokens.mjs: change the app's tokens or the")
line(" * script's SITE_ONLY block and re-run it, rather than editing this file.")
line(" *")
line(" * --ms-text-primary is Semantic/color/text/primary: Palette.textPrimary in")
line(" * Swift and text/primary in Figma. Light is the default, dark and Increased")
line(" * Contrast follow the visitor's system settings, as the app does.")
line(" */")
line(":root {")
line("  color-scheme: light dark;")
line()
line("  /* Primitives */")
primitives.forEach((l) => line(l))
line()
line("  /* Semantic colours (light) */")
modes.Light.forEach((l) => line(l))
line()
line("  /* Typography: size in px, line height as a ratio, tracking in em */")
typography.forEach((l) => line(l))
line()
line("  /* Spacing, radius, stroke */")
dimensions(tokens.Spacing.spacing, "space").forEach((l) => line(l))
dimensions(tokens.Radius.radius, "radius").forEach((l) => line(l))
dimensions(tokens.Stroke.stroke, "stroke").forEach((l) => line(l))
line()
line(SITE_ONLY)
line("}")
line()
line("@media (prefers-color-scheme: dark) {")
line("  :root {")
modes.Dark.forEach((l) => line("  " + l))
line("  }")
line("}")
line()
line("@media (prefers-contrast: more) {")
line("  :root {")
contrast.Light.forEach((l) => line(l))
line("  }")
line("}")
line()
line("@media (prefers-contrast: more) and (prefers-color-scheme: dark) {")
line("  :root {")
contrast.Dark.forEach((l) => line(l))
line("  }")
line("}")

process.stdout.write(out.join("\n") + "\n")
